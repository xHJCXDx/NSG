#!/usr/bin/env sh
# Records a short functional run of the running system into a dated log
# (see audit/rev76_verificacion/capturas_checklist.md).
# Read-only: it queries git, Docker and PostgreSQL and never changes data.
#
# Usage, from the repository root:
#   sh scripts/functional_run.sh --since "2026-11-20 14:00:00-03:00"
#   sh scripts/functional_run.sh --since "2026-11-20 14:00:00-03:00" --dry-run
#
#   --since    start of the run window, with its UTC offset (required)
#   --dry-run  print what would run; the system does not need to be up
#   --out-dir  directory for the log (default: audit/rev76_verificacion)
set -u
cd "$(dirname "$0")/.." || exit 1

CONTAINERS="osint-postgres osint-postgres-n8n osint-n8n osint-sentiment-api osint-dashboard-api osint-frontend osint-traefik"
DB_CONTAINER="osint-postgres"
HEALTH_URL="http://localhost/api/health"

since=""
dry_run=0
out_dir="audit/rev76_verificacion"

usage() { sed -n '6,12p' "$0" | sed 's/^# \{0,1\}//'; }
fail() { echo "error: $1" >&2; exit 2; }

while [ $# -gt 0 ]; do
  case "$1" in
    --since) [ $# -ge 2 ] || fail "--since needs a value"; since="$2"; shift 2 ;;
    --out-dir) [ $# -ge 2 ] || fail "--out-dir needs a value"; out_dir="$2"; shift 2 ;;
    --dry-run) dry_run=1; shift ;;
    -h | --help) usage; exit 0 ;;
    *) echo "error: unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

[ -n "$since" ] || fail "--since is required"
case "$since" in *'
'*) fail "--since must be a single line" ;; esac
# 'YYYY-MM-DD HH:MM[:SS]' plus a UTC offset (+HH:MM, -HH:MM or Z), so the
# window does not depend on the database time zone.
printf '%s\n' "$since" |
  grep -Eq '^[0-9]{4}-[0-9]{2}-[0-9]{2}[ T][0-9]{2}:[0-9]{2}(:[0-9]{2})?([+-][0-9]{2}(:?[0-9]{2})?|Z)$' ||
  fail "--since must look like '2026-11-20 14:00:00-03:00' (the UTC offset is required)"

log="$out_dir/corrida_funcional_$(date '+%Y%m%d-%H%M%S').log"
status=0

# Runs a read-only SQL statement in the application database, with :'since' bound.
query() {
  printf '%s\n' "$1" |
    docker exec -i -e PGOPTIONS='-c default_transaction_read_only=on' "$DB_CONTAINER" \
      sh -c 'psql -X -q -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v since="$1"' sh "$since"
}

# step TITLE COMMAND...: prints the command on --dry-run; otherwise appends
# the title and the command output to the log and remembers any failure.
step() {
  title="$1"
  shift
  if [ "$dry_run" -eq 1 ]; then
    printf '[dry-run] %s:' "$title"
    printf ' %s' "$@"
    printf '\n'
    return 0
  fi
  printf '\n== %s\n' "$title" >>"$log"
  if ! "$@" >>"$log" 2>&1; then
    printf '!! step failed: %s\n' "$title" >>"$log"
    status=1
  fi
}

SQL_ENV="SELECT version(); SHOW TimeZone; SELECT now() AS db_now;"
SQL_EXECUTIONS_BY_STATUS="SELECT status, count(*) AS executions
FROM execution_logs WHERE started_at >= :'since'::timestamptz
GROUP BY status ORDER BY status;"
SQL_EXECUTIONS="SELECT log_id, workflow_name, status, started_at, completed_at, duration_seconds,
  mentions_collected, mentions_processed, detections_generated, alerts_generated
FROM execution_logs WHERE started_at >= :'since'::timestamptz ORDER BY started_at;"
SQL_MENTIONS="SELECT CASE WHEN GROUPING(platform) = 1 THEN 'TOTAL' ELSE platform END AS source,
  count(*) AS mentions_persisted
FROM social_mentions WHERE collected_at >= :'since'::timestamptz
GROUP BY ROLLUP (platform) ORDER BY GROUPING(platform), platform;"
SQL_ALERTS="SELECT CASE WHEN GROUPING(delivery_status) = 1 THEN 'TOTAL'
  ELSE coalesce(delivery_status, '(none)') END AS delivery_status,
  count(*) AS alerts
FROM alerts WHERE created_at >= :'since'::timestamptz
GROUP BY ROLLUP (delivery_status) ORDER BY GROUPING(delivery_status), delivery_status NULLS LAST;"
SQL_ALERTS_SENT="SELECT count(*) AS alerts_sent
FROM alerts WHERE created_at >= :'since'::timestamptz AND delivery_status IN ('sent', 'delivered');"

not_recorded() {
  cat <<'EOF'
Not recorded because the prototype does not store them (declared limitations):
- status per source (responded, reception time, items, new items, incomplete
  GitHub results): matrix rows AD-91, R8A-08, R8A-46, R8B-13, R8B-31 and R8B-75;
- acquisition window saturation: matrix row AD-93.
Mentions per source are reported from social_mentions.platform instead.
EOF
}

if [ "$dry_run" -eq 1 ]; then
  echo "[dry-run] would write the log to: $log"
  echo "[dry-run] run window: from $since until the moment of the real run"
else
  [ -d "$out_dir" ] || fail "output directory not found: $out_dir"
  [ ! -e "$log" ] || fail "log already exists: $log"
  {
    echo "Functional run log - generated by scripts/functional_run.sh; do not edit."
    echo "Run window start (--since): $since"
    echo "Recorded at (local): $(date '+%Y-%m-%d %H:%M:%S %z')"
    echo "Recorded at (UTC):   $(date -u '+%Y-%m-%d %H:%M:%S')"
  } >"$log"
fi

step "Commit" git rev-parse HEAD
step "Uncommitted tracked changes (empty means clean)" \
  git -c core.fileMode=false status --porcelain --untracked-files=no
step "Docker server version" docker version --format '{{.Server.Version}}'
for c in $CONTAINERS; do
  step "Container $c" docker inspect \
    --format '{{.Name}} image={{.Config.Image}} image_id={{.Image}} state={{.State.Status}} started={{.State.StartedAt}}' "$c"
done
step "API health" curl -fsS --max-time 10 "$HEALTH_URL"
step "Database environment" query "$SQL_ENV"
step "Executions in the window, by status" query "$SQL_EXECUTIONS_BY_STATUS"
step "Executions in the window" query "$SQL_EXECUTIONS"
step "Mentions persisted in the window, by source" query "$SQL_MENTIONS"
step "Alerts in the window, by delivery status" query "$SQL_ALERTS"
step "Alerts sent in the window" query "$SQL_ALERTS_SENT"
step "Not recorded" not_recorded

if [ "$dry_run" -eq 0 ]; then
  echo "Log written to: $log"
  [ "$status" -eq 0 ] || echo "Some steps failed; see the lines starting with '!!' in the log." >&2
fi
exit "$status"
